def aliyun_translate_title(text):
    """调用阿里云翻译标题，返回中文翻译。失败返回空字符串"""
    ak_id = os.environ.get("ALIYUN_ACCESS_KEY_ID", "")
    ak_secret = os.environ.get("ALIYUN_ACCESS_KEY_SECRET", "")
    if not ak_id or not ak_secret:
        return ""

    import time, uuid, hashlib, hmac, base64 as b64, urllib.parse, urllib.request, ssl

    def _sign(params, secret):
        sorted_keys = sorted(params.keys())
        canonicalized = '&'.join(f'{urllib.parse.quote(k, safe="")}={urllib.parse.quote(params[k], safe="")}' for k in sorted_keys)
        string_to_sign = 'POST&%2F&' + urllib.parse.quote(canonicalized, safe='')
        signature = b64.b64encode(hmac.new((secret + '&').encode('utf-8'), string_to_sign.encode('utf-8'), hashlib.sha1).digest()).decode('utf-8')
        return signature

    params = {
        'Action': 'TranslateGeneral',
        'Version': '2018-10-12',
        'RegionId': 'cn-hangzhou',
        'FormatType': 'text',
        'SourceLanguage': 'en',
        'TargetLanguage': 'zh',
        'SourceText': text,
        'AccessKeyId': ak_id,
        'Timestamp': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
        'SignatureMethod': 'HMAC-SHA1',
        'SignatureVersion': '1.0',
        'SignatureNonce': str(uuid.uuid4()),
        'Format': 'JSON',
    }
    params['Signature'] = _sign(params, ak_secret)

    try:
        body = urllib.parse.urlencode(params).encode('utf-8')
        req = urllib.request.Request('https://mt.cn-hangzhou.aliyuncs.com/', data=body, method='POST',
            headers={'Content-Type': 'application/x-www-form-urlencoded'})
        ctx = ssl.create_default_context()
        resp = urllib.request.urlopen(req, context=ctx, timeout=15)
        result = json.loads(resp.read().decode('utf-8'))
        if result.get('Code') == '200':
            translated = result.get('Data', {}).get('Translated', '')
            if translated and translated.strip():
                return translated.strip()
    except Exception as e:
        print(f'[aliyun_translate_title] ERROR: {e}')

    return ""

