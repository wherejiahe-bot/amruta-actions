# 规则：
#   1. 用 LaBSE 做句子嵌入，余弦相似度 > THRESHOLD 视为重复
#   2. 如果两个重复句子长度相同 → 去哪个都行（保留第一个）
#   3. 如果长度不同 → 保留较长的，去除较短的
